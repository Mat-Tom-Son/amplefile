import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { prepareResourceEnable, resourceEnableAdapter } from "../src/local/agent/resource-enable-act.js";
import { listNativeResources } from "../src/local/agent/resource-lifecycle.js";
import { prepareAct } from "../src/local/prepared-acts.js";

test("resource enablement refuses changed source and settings before effect", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "amplefile-enable-pin-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const agentDir = join(root, "pi"), connectedFolder = join(root, "connected-folder");
  await mkdir(join(agentDir, "extensions"), { recursive: true }); await mkdir(connectedFolder);
  const path = join(agentDir, "extensions", "fixture.ts");
  await writeFile(path, "export default function() {}");
  const provider = { resolveRuntime: async () => ({ agentDir, projectTrust: { override: true } }) };
  const input = { path, kind: "extensions" as const, enabled: false, scope: "everywhere" as const };
  const adapter = resourceEnableAdapter(async () => connectedFolder, provider);
  const sourceAct = await prepareResourceEnable(connectedFolder, input, provider);
  await writeFile(path, "export default function() { /* changed */ }");
  assert.match((await adapter.recheckPins(sourceAct))!, /changed/);
  await assert.rejects(adapter.execute(sourceAct), /changed/);
  const settingsAct = await prepareResourceEnable(connectedFolder, input, provider);
  await writeFile(join(agentDir, "settings.json"), JSON.stringify({ theme: "light" }));
  assert.match((await adapter.recheckPins(settingsAct))!, /changed/);
  assert.equal((await listNativeResources(connectedFolder, provider)).find((item) => item.path === path)?.enabled, true);
  const current = await prepareResourceEnable(connectedFolder, input, provider);
  assert.equal(await adapter.recheckPins(current), null);
  await adapter.execute(current);
  assert.equal((await listNativeResources(connectedFolder, provider)).find((item) => item.path === path)?.enabled, false);
  assert.throws(() => prepareAct({ ...current, parameters: { ...current.parameters, scope: "connected-folder" }, pins: { ...current.pins, scope: "connected-folder" } }), /connectedFolderId/);
});
